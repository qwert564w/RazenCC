   public static String ui(String english) {
      return ui(english, Map.of());
   }

   private static String ui(String english, Map<String, String> russianOverrides) {
      if (english != null && UiLanguage.current() != UiLanguage.ENGLISH) {
         String localized = lookup(uiOverrides(), english);
         if (localized != null) {
            return localized;
         }

         String override = lookup(russianOverrides, english);
         return override != null ? override : UI_RU.getOrDefault(english, english);
      } else {
         return english;
      }
   }

   public static String days(int count) {
      return switch (UiLanguage.current()) {
         case ENGLISH -> count == 1 ? "Day" : "Days";
         case UKRAINIAN -> slavicPlural(count, "день", "дні", "днів");
         case POLISH -> slavicPlural(count, "dzień", "dni", "dni");
         case KAZAKH -> "күн";
         case RUSSIAN -> slavicPlural(count, "день", "дня", "дней");
      };
   }

   private static String slavicPlural(int count, String one, String few, String many) {
      int mod100 = Math.abs(count) % 100;
      if (mod100 >= 11 && mod100 <= 14) {
         return many;
      }

      return switch (mod100 % 10) {
         case 1 -> one;
         case 2, 3, 4 -> few;
         default -> many;
      };
   }

   public static String setting(String canonicalName) {
      if (canonicalName == null) {
         return null;
      }

      if (UiLanguage.current() == UiLanguage.ENGLISH) {
         return SETTING_EN.getOrDefault(canonicalName, canonicalName);
      }

      String localized = lookup(settingOverrides(), canonicalName);
      return localized != null ? localized : SETTING_RU.getOrDefault(canonicalName, PVE_SETTING_RU.getOrDefault(canonicalName, canonicalName));
   }

